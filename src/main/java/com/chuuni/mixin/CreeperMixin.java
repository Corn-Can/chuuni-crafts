/** 用打火石點燃苦力怕 → CREEPER */
@Mixin(net.minecraft.world.entity.monster.Creeper.class)
public abstract class CreeperMixin {
	@Inject(method = "ignite", at = @At("HEAD"))
	private void chuuni$ignite(CallbackInfo ci) {
		Entity self = (Entity)(Object)this;
		Triggers.mob(self.level(), Kind.CREEPER, self, 1, 0, null, ItemStack.EMPTY, 20);
	}
}
