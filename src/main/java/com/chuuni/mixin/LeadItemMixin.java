/** 把拴著的生物綁到柵欄 → LEASH 1（C 級） */
@Mixin(net.minecraft.world.item.LeadItem.class)
public abstract class LeadItemMixin {
	@Inject(method = "bindPlayerMobs", at = @At("RETURN"))
	private static void chuuni$fence(Player player, Level level, BlockPos pos, CallbackInfoReturnable<InteractionResult> cir) {
		if (cir.getReturnValue().consumesAction()) {
			Triggers.minor(level, Kind.LEASH, pos, 1, 0, 1, player, ItemStack.EMPTY, null, -1, 2);
		}
	}
}
