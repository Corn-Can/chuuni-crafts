@Mixin(LecternBlock.class)
public abstract class LecternBlockMixin {
	@Inject(method = "tryPlaceBook", at = @At("RETURN"))
	private static void chuuni$place(LivingEntity entity, Level level, BlockPos pos, BlockState state, ItemStack stack, CallbackInfoReturnable<Boolean> cir) {
		if (cir.getReturnValueZ()) {
			Triggers.minor(level, Kind.LECTERN, pos, 0, 0, 0, entity, stack, null, -1, 4);
		}
	}
}
